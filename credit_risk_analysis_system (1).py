# New applicant prediction
def predict_risk(age, income, home, employment, purpose,
                 loan, interest, previous_default, history):

    applicant = pd.DataFrame([{
        "person_age": age,
        "person_income": income,
        "person_home_ownership": home,
        "person_emp_length": employment,
        "loan_intent": purpose,
        "loan_amnt": loan,
        "loan_int_rate": interest,
        "loan_percent_income": loan / income if income > 0 else 0,
        "cb_person_default_on_file": previous_default,
        "cb_person_cred_hist_length": history
    }])

    prediction = model.predict(applicant)[0]

    if hasattr(model, "predict_proba"):
        probability = model.predict_proba(applicant)[0][1] * 100
    else:
        probability = None

    if prediction == 1:
        risk = "Higher predicted default risk"
        recommendation = "Manual review recommended"
    else:
        risk = "Lower predicted default risk"
        recommendation = "Further review before any loan decision"

    if probability is not None:
        result = f"{risk}\nEstimated default probability: {probability:.2f}%"
    else:
        result = risk

    return result, recommendation


